/** segments: [["silence"|"tone"|"noise", seconds], ...] -> 8 kHz mono PCM wav generated by ffmpeg (no meeting audio). */
export function synthAudio(file, segments) {
  const inputs = segments.flatMap(([kind, d]) => ["-f", "lavfi", "-i", kind === "silence" ? `anullsrc=r=8000:cl=mono:d=${d}` :
    kind === "noise" ? `anoisesrc=r=8000:a=0.05:d=${d}` : `sine=f=440:r=8000:d=${d}`]);
  const r = spawnSync("ffmpeg", ["-hide_banner", "-y", ...inputs, "-filter_complex", `${segments.map((_, i) => `[${i}]`).join("")}concat=n=${segments.length}:v=0:a=1`,
    "-ac", "1", "-c:a", "pcm_s16le", "-f", "wav", file], { encoding: "utf8", windowsHide: true });
  if (r.status !== 0) throw new Error(r.stderr);
  return file;
}
