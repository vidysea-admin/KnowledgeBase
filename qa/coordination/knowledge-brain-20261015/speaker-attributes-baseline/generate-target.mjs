// Deferred source-only command; execute only after central releases shared schema freeze.
import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
const schemaDir = resolve("schema"), name = "speaker_attributes";
const schema = JSON.parse(readFileSync(join(schemaDir, `${name}.schema.json`), "utf8"));
const kb = {
  order: 1,
  canRead: /^kb:\/\//,
  read(file) {
    const name = file.url.replace(/^kb:\/\//, "").replace(/[#/].*$/, "");
    return readFileSync(join(schemaDir, `${name}.schema.json`), "utf8");
  },
};
const output = (await compile(schema, name, {
  bannerComment: `/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from schema/${name}.schema.json — DO NOT EDIT.\n * Run \`pnpm gen:types\` after changing the schema.\n */`,
  additionalProperties: true,
  $refOptions: { resolve: { kb } },
  cwd: schemaDir,
  style: { printWidth: 100 },
})).replace(/\r\n/g, "\n");
writeFileSync(`packages/core/src/generated/${name}.ts`, output, "utf8");
console.log(`Generated only ${name}.ts with exact gen-types.mjs compile options`);
